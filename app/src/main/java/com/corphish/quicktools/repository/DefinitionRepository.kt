    override suspend fun getDefinition(word: String): List<WordDefinition>? = withContext(Dispatchers.IO) {
        val upperWord = word.trim().uppercase()
        if (slangMap.containsKey(upperWord)) {
            return@withContext listOf(
                WordDefinition(
                    word = word,
                    meanings = listOf(
                        Meaning(
                            partOfSpeech = "slang",
                            definitions = listOf(Definition(definition = slangMap[upperWord]!!))
                        )
                    ),
                    source = DefinitionSource.LOCAL_SLANG
                )
            )
        }

        // 1. Try Free Dictionary API
        val dictionaryResult = queryDictionaryApi(word)
        if (dictionaryResult != null) return@withContext dictionaryResult

        // 2. Fallback to Wiktionary
        return@withContext queryWiktionaryApi(word)
    }

    private fun queryDictionaryApi(word: String): List<WordDefinition>? {
        try {
            val url = URL("https://api.dictionaryapi.dev/api/v2/entries/en/${word.trim()}")
            val connection = url.openConnection() as HttpURLConnection
            connection.requestMethod = "GET"
            connection.connectTimeout = 5000
            connection.readTimeout = 5000

            if (connection.responseCode == 200) {
                val response = connection.inputStream.bufferedReader().use { it.readText() }
                return parseDefinition(response, DefinitionSource.DICTIONARY_API)
            }
        } catch (e: Exception) {
            e.printStackTrace()
        }
        return null
    }

    private fun queryWiktionaryApi(word: String): List<WordDefinition>? {
        try {
            val url = URL("https://en.wiktionary.org/api/rest_v1/page/definition/${word.trim()}")
            val connection = url.openConnection() as HttpURLConnection
            connection.requestMethod = "GET"
            connection.connectTimeout = 5000
            connection.readTimeout = 5000

            if (connection.responseCode == 200) {
                val response = connection.inputStream.bufferedReader().use { it.readText() }
                return parseWiktionaryDefinition(response)
            }
        } catch (e: Exception) {
            e.printStackTrace()
        }
        return null
    }

    private fun parseDefinition(json: String, source: DefinitionSource): List<WordDefinition> {
        val result = mutableListOf<WordDefinition>()
        val rootArray = JSONArray(json)
        for (i in 0 until rootArray.length()) {
            val wordObj = rootArray.getJSONObject(i)
            val word = wordObj.getString("word")
            val phonetic = if (wordObj.has("phonetic")) wordObj.getString("phonetic") else null
            
            val meanings = mutableListOf<Meaning>()
            val meaningsArray = wordObj.getJSONArray("meanings")
            for (j in 0 until meaningsArray.length()) {
                val meaningObj = meaningsArray.getJSONObject(j)
                val partOfSpeech = meaningObj.getString("partOfSpeech")
                
                val definitions = mutableListOf<Definition>()
                val definitionsArray = meaningObj.getJSONArray("definitions")
                for (k in 0 until definitionsArray.length()) {
                    val defObj = definitionsArray.getJSONObject(k)
                    definitions.add(
                        Definition(
                            definition = defObj.getString("definition"),
                            example = if (defObj.has("example")) defObj.getString("example") else null
                        )
                    )
                }
                meanings.add(Meaning(partOfSpeech, definitions))
            }
            result.add(WordDefinition(word, phonetic, meanings, source))
        }
        return result
    }

    private fun parseWiktionaryDefinition(json: String): List<WordDefinition> {
        val result = mutableListOf<WordDefinition>()
        val rootObj = org.json.JSONObject(json)
        val word = rootObj.keys().next() // Wiktionary returns language-keyed object, e.g. {"en": [...]}
        val languageArray = rootObj.getJSONArray(word)
        
        val meanings = mutableListOf<Meaning>()
        for (i in 0 until languageArray.length()) {
            val entry = languageArray.getJSONObject(i)
            val partOfSpeech = entry.getString("partOfSpeech")
            
            val definitions = mutableListOf<Definition>()
            val defsArray = entry.getJSONArray("definitions")
            for (j in 0 until defsArray.length()) {
                val defObj = defsArray.getJSONObject(j)
                val definitionText = defObj.getString("definition")
                    .replace(Regex("<[^>]*>"), "") // Strip HTML tags
                
                val examples = if (defObj.has("examples")) {
                    val examplesArray = defObj.getJSONArray("examples")
                    if (examplesArray.length() > 0) {
                        examplesArray.getString(0).replace(Regex("<[^>]*>"), "")
                    } else null
                } else null
                
                definitions.add(Definition(definitionText, examples))
            }
            meanings.add(Meaning(partOfSpeech, definitions))
        }
        result.add(WordDefinition(word, meanings = meanings, source = DefinitionSource.WIKTIONARY))
        return result
    }
